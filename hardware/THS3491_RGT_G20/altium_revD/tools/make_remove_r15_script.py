"""Generate the native, narrowly scoped output-load removal script."""
from pathlib import Path
import argparse

ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--directory',type=Path,required=True)
a=p.parse_args();d=a.directory.resolve();d.mkdir(parents=True,exist_ok=True)
script=r'''
Procedure RemoveOutputLoadPCB;
Var Doc:IServerDocument; Board:IPCB_Board; It:IPCB_BoardIterator;
 Comp,Target:IPCB_Component; Region:IPCB_Region; Cutout:IPCB_Region;
 Box:TCoordRect; Report:TStringList; FileName,LogFile:String; N:Integer;
Begin
 FileName:='__DIR__\without_R15.PcbDoc';LogFile:='__DIR__\remove_pcb.txt';
 Report:=TStringList.Create;Report.Add('START');Report.SaveToFile(LogFile);
 Doc:=Client.OpenDocument('PCB',FileName);If Doc=Nil Then Exit;
 If Doc.Modified Then Begin Report.Add('ABORT unsaved changes');Report.SaveToFile(LogFile);Exit;End;
 Client.ShowDocument(Doc);Board:=PCBServer.GetPCBBoardByPath(FileName);If Board=Nil Then Exit;
 Target:=Nil;N:=0;It:=Board.BoardIterator_Create;
 It.AddFilter_ObjectSet(MkSet(eComponentObject));It.AddFilter_LayerSet(AllLayers);It.AddFilter_Method(eProcessAll);
 Comp:=It.FirstPCBObject;
 While Comp<>Nil Do Begin
  If Comp.Name.Text='R15' Then Begin Target:=Comp;Inc(N);End;
  Comp:=It.NextPCBObject;
 End;Board.BoardIterator_Destroy(It);
 Report.Add('R15='+IntToStr(N));Report.SaveToFile(LogFile);If N<>1 Then Exit;
 Cutout:=Nil;N:=0;It:=Board.BoardIterator_Create;
 It.AddFilter_ObjectSet(MkSet(eRegionObject));It.AddFilter_LayerSet(MkSet(eMidLayer1));It.AddFilter_Method(eProcessAll);
 Region:=It.FirstPCBObject;
 While Region<>Nil Do Begin
  Box:=Region.BoundingRectangle;
  If (Region.Kind=1) And (Abs(Box.Left+Box.Right-MMsToCoord(62))<100)
   And (Abs(Box.Top+Box.Bottom-MMsToCoord(81.28))<100) Then Begin Cutout:=Region;Inc(N);End;
  Region:=It.NextPCBObject;
 End;Board.BoardIterator_Destroy(It);
 Report.Add('R15 L2 cutouts='+IntToStr(N));Report.SaveToFile(LogFile);If N<>1 Then Exit;
 PCBServer.PreProcess;
 Try
  Board.RemovePCBObject(Target);
  PCBServer.SendMessageToRobots(Board.I_ObjectAddress,c_Broadcast,PCBM_BoardRegisteration,Target.I_ObjectAddress);
  Board.RemovePCBObject(Cutout);
  PCBServer.SendMessageToRobots(Board.I_ObjectAddress,c_Broadcast,PCBM_BoardRegisteration,Cutout.I_ObjectAddress);
 Finally PCBServer.PostProcess;End;
 Board.ViewManager_FullUpdate;
 If Not Doc.DoFileSave('PCB Binary') Then Exit;
 Report.Add('SAVED');Report.SaveToFile(LogFile);Client.CloseDocument(Doc);
 Doc:=Client.OpenDocument('PCB',FileName);If Doc=Nil Then Exit;Client.ShowDocument(Doc);
 Report.Add('REOPENED');Report.SaveToFile(LogFile);Report.Free;
End;

Procedure RemoveOutputLoadSCH;
Var Doc:IServerDocument; Sheet:ISch_Document; It:ISch_Iterator;
 Obj:ISch_GraphicalObject; Comp:ISch_Component; Note:ISch_Label;
 Items:TInterfaceList; Report:TStringList; FileName,LogFile,Id:String; I:Integer;
Begin
 FileName:='__DIR__\without_R15.SchDoc';LogFile:='__DIR__\remove_sch.txt';
 Report:=TStringList.Create;Report.Add('START');Report.SaveToFile(LogFile);
 Doc:=Client.OpenDocument('SCH',FileName);If Doc=Nil Then Exit;
 If Doc.Modified Then Begin Report.Add('ABORT unsaved changes');Report.SaveToFile(LogFile);Exit;End;
 Client.ShowDocument(Doc);Sheet:=SchServer.GetCurrentSchDocument;If Sheet=Nil Then Exit;
 Items:=TInterfaceList.Create;Note:=Nil;It:=Sheet.SchIterator_Create;
 It.AddFilter_ObjectSet(MkSet(eSchComponent,eWire,eJunction,eNetLabel,ePowerObject,eLabel));
 Obj:=It.FirstSchObject;
 While Obj<>Nil Do Begin
  Id:=Obj.UniqueId;
  If (Id='WIGXTQTA') Or (Id='ZFXXKETI') Or (Id='QDKCBLYZ') Or (Id='GBCRHJRD') Or (Id='POFBJDVA') Then Begin Items.Add(Obj);Report.Add('MATCH '+Id);End;
  If Id='OUOOBONS' Then Note:=Obj;
  Obj:=It.NextSchObject;
 End;Sheet.SchIterator_Destroy(It);
 Report.Add('Objects='+IntToStr(Items.Count));Report.SaveToFile(LogFile);
 { Junctions may be regenerated by Altium and absent from the iterator. }
 If ((Items.Count<>4) And (Items.Count<>5)) Or (Note=Nil) Then Exit;
 SchServer.ProcessControl.PreProcess(Sheet,'');
 Try
  For I:=0 To Items.Count-1 Do Begin
   Obj:=Items.Items[I];Sheet.RemoveSchObject(Obj);
   SchServer.RobotManager.SendMessage(Sheet.I_ObjectAddress,c_BroadCast,SCHM_PrimitiveRegistration,Obj.I_ObjectAddress);
  End;
  SchServer.RobotManager.SendMessage(Note.I_ObjectAddress,c_BroadCast,SCHM_BeginModify,c_NoEventData);
  Note.Text:='Output attenuator R9-R13 removed. R14=49.9 ohm series; R15 local load removed.';
  SchServer.RobotManager.SendMessage(Note.I_ObjectAddress,c_BroadCast,SCHM_EndModify,c_NoEventData);
 Finally SchServer.ProcessControl.PostProcess(Sheet,'');End;
 Items.Free;Sheet.GraphicallyInvalidate;
 If Not Doc.DoFileSave('SCH Binary') Then Exit;
 Report.Add('SAVED');Report.SaveToFile(LogFile);Client.CloseDocument(Doc);
 Doc:=Client.OpenDocument('SCH',FileName);If Doc=Nil Then Exit;Client.ShowDocument(Doc);
 Report.Add('REOPENED');Report.SaveToFile(LogFile);Report.Free;
End;
'''.replace('__DIR__',str(d))
(d/'RemoveR15.pas').write_text(script,encoding='utf-8')
(d/'RemoveR15.PrjScr').write_text('[Design]\nVersion=1.0\n[Document1]\nDocumentPath=RemoveR15.pas\n')
print(d/'RemoveR15.PrjScr')
